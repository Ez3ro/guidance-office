class TimeStampedModel(models.Model):
    """Adds created/updated timestamps and the user who made each change."""

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        editable=False,
        on_delete=models.PROTECT,
        related_name="+",
    )
    updated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        editable=False,
        on_delete=models.PROTECT,
        related_name="+",
    )

    class Meta:
        abstract = True

    def save(self, *args, **kwargs):
        # Records generated by the system (e.g. deadline follow-ups) aren't attributed
        # to whoever happened to trigger them.
        user = None if getattr(self, "_system_change", False) else get_current_user()
        if user is not None:
            if self._state.adding and self.created_by_id is None:
                self.created_by = user
            self.updated_by = user
        update_fields = kwargs.get("update_fields")
        if update_fields is not None:
            extra = {"updated_at", "updated_by"} if user is not None else {"updated_at"}
            kwargs["update_fields"] = set(update_fields) | extra
        super().save(*args, **kwargs)


class SchoolProfile(models.Model):
    """Single row holding the school details printed on reports and forms."""

    name = models.CharField("School name", max_length=200, default="Name of School")
    school_id = models.CharField("School ID", max_length=20, blank=True)
    district = models.CharField(max_length=120, blank=True)
    division = models.CharField("Schools Division Office", max_length=120, blank=True)
    region = models.CharField(max_length=120, blank=True)
    address = models.CharField(max_length=255, blank=True)
    school_head_name = models.CharField("School head", max_length=150, blank=True)
    school_head_position = models.CharField(max_length=120, blank=True, default="School Principal")
    guidance_head_name = models.CharField(
        "Guidance counselor / coordinator", max_length=150, blank=True
    )
    contact_number = models.CharField(max_length=60, blank=True)
    email = models.EmailField(blank=True)

    class Meta:
        verbose_name = "school profile"
        verbose_name_plural = "school profile"

    def __str__(self) -> str:
        return self.name

    def save(self, *args, **kwargs):
        self.pk = 1
        super().save(*args, **kwargs)

    def delete(self, *args, **kwargs):
        return 0, {}

    @classmethod
    def load(cls) -> SchoolProfile:
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj


class NumberSequence(models.Model):
    """Gap-free yearly counters for case numbers such as CP-2026-0001."""

    key = models.CharField(max_length=40, unique=True)
    last_value = models.PositiveIntegerField(default=0)

    def __str__(self) -> str:
        return f"{self.key}: {self.last_value}"


def next_reference(prefix: str, year: int | None = None) -> str:
    year = year or timezone.localdate().year
    key = f"{prefix}-{year}"
    for _attempt in range(3):
        try:
            with transaction.atomic():
                seq, _ = NumberSequence.objects.select_for_update().get_or_create(key=key)
                seq.last_value += 1
                seq.save(update_fields=["last_value"])
                return f"{key}-{seq.last_value:04d}"
        except IntegrityError:  # two requests created the counter at once; retry
            continue
    raise RuntimeError(f"Could not allocate a number for {key}")


def attachment_upload_to(instance: Attachment, filename: str) -> str:
    # Storage keys never contain the original file name, which may include a learner's name.
    ext = Path(filename).suffix.lower()[:10]
    ct = instance.content_type
    return f"attachments/{ct.app_label}/{ct.model}/{uuid.uuid4().hex}{ext}"


class Attachment(TimeStampedModel):
    """A file attached to a case, session or plan. Downloads are permission-checked."""

    content_type = models.ForeignKey(ContentType, on_delete=models.PROTECT)
    object_id = models.PositiveBigIntegerField()
    content_object = GenericForeignKey("content_type", "object_id")
    file = models.FileField(upload_to=attachment_upload_to, max_length=255)
    original_name = EncryptedTextField()
    size = models.PositiveIntegerField(default=0)
    mime_type = models.CharField(max_length=100, blank=True)
    description = models.CharField(max_length=255, blank=True)

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["content_type", "object_id"])]

    def __str__(self) -> str:
        return f"Attachment #{self.pk}"
